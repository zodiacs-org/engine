// Writes src/minor-bodies/pack-data.ts, the tables of @zodiacs/engine/minor-bodies,
// from the files scripts/minor-bodies/fetch-horizons.py and fit.py leave in one
// directory (by default .cache/minor-bodies/, which git ignores):
//
//   node scripts/minor-bodies/build-pack-data.mjs [--data DIR]
//
// It checks each raw VECTORS response there against the SHA-256 and size
// provenance.json records, that fitted-pack.json was fitted to those very
// responses (fit.py records the SHA-256 of the file it read for each body as
// vectorsSha256), and each body's table against the layout fitted-pack.json
// gives it, then writes one base64 constant, its description and the Horizons
// solution it was fitted to per body into pack-data.ts, so that a bundler that
// is given one body's spec keeps that body's table alone, and the provenance
// as a constant; and copies provenance.json to src/minor-bodies/provenance.json
// and oos-observer-100.json to src/fixtures/minor-bodies-horizons-oos.json,
// byte for byte. Regenerate the files this way; never edit them by hand.
// scripts/minor-bodies/build-pack-data.test.mjs checks that the committed
// pack-data.ts is this script's text for its own tables and provenance.json.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { copyFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REPOSITORY = fileURLToPath(new URL("../..", import.meta.url));

export const BODIES = ["Chiron", "Ceres", "Pallas", "Juno", "Vesta"];
/**
 * The fields of each body that MINOR_BODIES_PROVENANCE documents (src/minor-bodies.ts,
 * MinorBodiesProvenance), in its order. Any other field provenance.json records for a
 * body, as the fetchedAtUtc fetch-horizons.py writes, stays out of the constant.
 */
export const PUBLIC_BODY_FIELDS = ["command", "step", "rows", "bytes", "sha256", "solution", "record", "target"];
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");
const constant = (name) => name.toUpperCase();

/** The solution a body's entry in provenance.json names, as Horizons writes it ("JPL#171"). */
function solutionOf(name, recorded) {
  const id = /JPL#\d+/u.exec(recorded.solution ?? "")?.[0];
  assert(id, `${name}: provenance.json names no JPL solution`);
  return id;
}

/** Checks each raw VECTORS response (`vectors(name)` gives its bytes) against the size and SHA-256 provenance.json records. */
export function checkVectors(provenance, vectors) {
  assert.deepEqual(Object.keys(provenance.bodies), BODIES, "provenance.json must hold the five bodies in order");
  for (const name of BODIES) {
    const raw = vectors(name);
    const recorded = provenance.bodies[name];
    assert.equal(raw.length, recorded.bytes, `${name}: the raw response is not the size provenance.json records`);
    assert.equal(sha256(raw), recorded.sha256, `${name}: the raw response's SHA-256 is not the one provenance.json records`);
  }
}

/**
 * The text of src/minor-bodies/pack-data.ts for provenance.json and fitted-pack.json, read as
 * JSON. Refused where fitted-pack.json does not record that it was fitted to the response
 * provenance.json records for a body (its vectorsSha256 missing, or another response's: a
 * fit left from earlier vectors), or where a table is not what its layout says.
 */
export function packDataText(provenance, fitted) {
  assert.equal(fitted.format, "ZODMB01", "fitted-pack.json is not a ZODMB01 pack");
  assert.deepEqual(Object.keys(fitted.bodies), BODIES, "fitted-pack.json must hold the five bodies in order");
  assert.deepEqual(Object.keys(provenance.bodies), BODIES, "provenance.json must hold the five bodies in order");
  for (const name of BODIES) {
    const fittedTo = fitted.bodies[name].vectorsSha256;
    const recorded = provenance.bodies[name].sha256;
    assert(
      typeof fittedTo === "string",
      `${name}: fitted-pack.json does not record the SHA-256 of the vectors it was fitted to (vectorsSha256): run scripts/minor-bodies/fit.py again`
    );
    assert.equal(
      fittedTo,
      recorded,
      `${name}: fitted-pack.json was fitted to other vectors (vectorsSha256 ${fittedTo}) than the response provenance.json records (sha256 ${recorded}): run scripts/minor-bodies/fit.py again`
    );
  }

  const combined = Buffer.from(fitted.base64, "base64");
  assert.equal(combined.length, fitted.totalRawBytes, "the fitted pack's bytes are not the size it records");
  const lines = [
    "// Generated by scripts/minor-bodies/build-pack-data.mjs from the fit of",
    "// scripts/minor-bodies/fit.py to NASA JPL Horizons vectors; do not edit by hand.",
    "//",
    "// Each body's table (ZODMB01): Chebyshev series of its heliocentric",
    "// position in the ICRF, km, over uniform intervals of TDB Julian days from",
    "// spanStartJd to spanEndJd, packed column by column (for each axis x, y, z,",
    "// for each coefficient k, every interval's) as little-endian int32 where",
    "// k < k32, int16 where k < k8Start and int8 beyond, each a multiple of",
    "// unitKm. src/minor-bodies/table.ts reads it. sha256 is the table's bytes'.",
    ""
  ];
  let at = 0;
  for (const name of BODIES) {
    const body = fitted.bodies[name];
    assert.equal(body.offset, at, `${name}: the tables must follow each other`);
    const widths = Array.from({ length: body.degree + 1 }, (_, k) => (k < body.k32 ? 4 : k < body.k8Start ? 2 : 1));
    assert.equal(body.bytes, 3 * body.intervals * widths.reduce((sum, width) => sum + width, 0), `${name}: the table's size is not its layout's`);
    assert(Math.abs(body.intervals * body.intervalDays - (fitted.spanEndJd - fitted.spanStartJd)) < 1e-6, `${name}: the intervals do not tile the span`);
    const bytes = combined.subarray(body.offset, body.offset + body.bytes);
    at += body.bytes;
    const id = solutionOf(name, provenance.bodies[name]);
    lines.push(
      `/** ${provenance.bodies[name].target.replace(/\s+\{.*$/u, "")}: its table, ${bytes.length} bytes as base64, fitted to Horizons's solution ${id}. */`,
      `export const ${constant(name)}_PACK =`,
      `  ${JSON.stringify(bytes.toString("base64"))};`,
      `/** The Horizons solution ${constant(name)}_PACK was fitted to, as PROVENANCE names it. */`,
      `export const ${constant(name)}_SOLUTION = ${JSON.stringify(id)};`,
      `/** How ${constant(name)}_PACK is laid out, the span it covers and its fit's largest error at the fitted vectors, km. */`,
      `export const ${constant(name)}_LAYOUT = {`,
      `  intervals: ${body.intervals},`,
      `  intervalDays: ${body.intervalDays},`,
      `  degree: ${body.degree},`,
      `  unitKm: ${body.unitKm},`,
      `  k32: ${body.k32},`,
      `  k8Start: ${body.k8Start},`,
      `  spanStartJd: ${fitted.spanStartJd},`,
      `  spanEndJd: ${fitted.spanEndJd},`,
      `  maxFitResidualKm: ${body.maxFitResidualKm},`,
      `  sha256: ${JSON.stringify(sha256(bytes))}`,
      "} as const;",
      ""
    );
  }
  assert.equal(at, combined.length, "the fitted pack holds bytes past its five tables");

  /** A JSON value as TypeScript source, each object frozen where it is made, with the mark that lets a bundler drop it unread; keys bare where they are identifiers. */
  const frozenSource = (value, indent = "") => {
    if (value === null || typeof value !== "object") return JSON.stringify(value);
    const inner = `${indent}  `;
    const key = (name) => (/^[A-Za-z_$][\w$]*$/u.test(name) ? name : JSON.stringify(name));
    const entries = Object.entries(value).map(([name, entry]) => `${inner}${key(name)}: ${frozenSource(entry, inner)}`);
    return `/*#__PURE__*/ Object.freeze({\n${entries.join(",\n")}\n${indent}})`;
  };
  const provenanceText = frozenSource({
    api: provenance.api,
    fetchedAtUtc: provenance.fetchedAtUtc,
    vectorParams: provenance.vectorParams,
    bodies: Object.fromEntries(
      BODIES.map((name) => {
        const body = provenance.bodies[name];
        return [name, Object.fromEntries(PUBLIC_BODY_FIELDS.map((field) => [field, field === "solution" ? solutionOf(name, body) : body[field]]))];
      })
    )
  });
  lines.push(
    "/** Where the tables come from: the Horizons query, and each raw response's size, SHA-256 and solution (src/minor-bodies/provenance.json). */",
    `export const PROVENANCE = ${provenanceText};`,
    ""
  );
  return lines.join("\n");
}

function main(args) {
  const flag = args.indexOf("--data");
  const data = flag === -1 ? join(REPOSITORY, ".cache", "minor-bodies") : args[flag + 1];
  assert(data, "--data needs a directory");
  const read = (name) => {
    const path = join(data, name);
    assert(existsSync(path), `${path} is missing: run scripts/minor-bodies/fetch-horizons.py and fit.py first`);
    return readFileSync(path);
  };
  const provenance = JSON.parse(read("provenance.json").toString("utf8"));
  const fitted = JSON.parse(read("fitted-pack.json").toString("utf8"));
  read("oos-observer-100.json");
  checkVectors(provenance, (name) => read(`${name.toLowerCase()}-vectors.txt`));
  const text = packDataText(provenance, fitted);
  writeFileSync(join(REPOSITORY, "src", "minor-bodies", "pack-data.ts"), text);
  copyFileSync(join(data, "provenance.json"), join(REPOSITORY, "src", "minor-bodies", "provenance.json"));
  copyFileSync(join(data, "oos-observer-100.json"), join(REPOSITORY, "src", "fixtures", "minor-bodies-horizons-oos.json"));
  console.log(`wrote src/minor-bodies/pack-data.ts (${fitted.totalRawBytes} bytes of tables) and copied provenance.json and the observer checks`);
}

const direct = process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));
if (direct) main(process.argv.slice(2));
