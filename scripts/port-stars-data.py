#!/usr/bin/env python3
"""Write src/stars-data.ts from Ephemera's data/stars_data.cpp (development only).

Ephemera (https://github.com/intellecat/ephemera, MIT, Copyright (c) 2026
Intellecat) built that catalogue with tools/make_stars.py from public data:
the Hipparcos new reduction (van Leeuwen 2007, VizieR I/311), SIMBAD radial
velocities and the IAU Working Group on Star Names list, carried to J2000.0
with ERFA's pmsafe. Ported from commit ce1bc21c7f9e1da150cd6e012d01474073147b15,
stars_data.cpp sha256
25d39822c005cb7524d2dd2c6dbe21aaab9920e6e53767984c46ce79c50aa25e.

    python3 scripts/port-stars-data.py /path/to/ephemera/data/stars_data.cpp
"""
import hashlib
import json
import re
import sys

SHA = "25d39822c005cb7524d2dd2c6dbe21aaab9920e6e53767984c46ce79c50aa25e"
src = open(sys.argv[1], "rb").read()
if hashlib.sha256(src).hexdigest() != SHA:
    sys.exit("stars_data.cpp does not match the pinned sha256")
row = re.compile(r'^\s*\{"([^"]*)", "([^"]*)", (\d+), ([-\d.]+)f, ([-\d.]+), ([-\d.]+), '
                 r'([-\d.]+)f, ([-\d.]+)f, ([-\d.]+)f, ([-\d.]+)f\},$', re.M)
rows = row.findall(src.decode())
assert len(rows) == 411, len(rows)
out = [
    "/*",
    " * Generated by scripts/port-stars-data.py from Ephemera's data/stars_data.cpp.",
    " * Do not edit.",
    " *",
    " * Ported from Ephemera, https://github.com/intellecat/ephemera",
    " * Copyright (c) 2026 Intellecat. MIT License: see NOTICE.",
    " *",
    " * Source data: Hipparcos, the new reduction (ESA; F. van Leeuwen 2007,",
    " * VizieR I/311), radial velocities from SIMBAD (CDS, Strasbourg), names from",
    " * the IAU Working Group on Star Names. Acknowledgements are in NOTICE.",
    " */",
    "",
    "/**",
    " * One row per star: IAU name, Bayer or Flamsteed designation (or \"\"),",
    " * Hipparcos number (0 for none), V magnitude, ICRS right ascension and",
    " * declination at J2000.0 (radians), proper motion in RA times cos(dec) and",
    " * in declination (mas/yr), parallax (mas), radial velocity (km/s).",
    " */",
    "export type StarRow = readonly [string, string, number, number, number, number, number, number, number, number];",
    "",
    "export const STAR_ROWS: readonly StarRow[] = [",
]
for r in rows:
    vals = [json.dumps(r[0]), json.dumps(r[1]), r[2]] + [repr(float(x)) for x in r[3:]]
    out.append("  [" + ", ".join(vals) + "],")
out.append("];")
open("src/stars-data.ts", "w").write("\n".join(out) + "\n")
print(len(rows))
