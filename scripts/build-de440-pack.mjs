// The generator of src/de440/pack-data.ts, the sealed DE440 pack that
// @zodiacs/engine/de440/pack ships (docs/de440.md).
//
//   node scripts/build-de440-pack.mjs <path to de440-1790-2210.v2.zeph>   # write the file
//   node scripts/build-de440-pack.mjs --check                            # check the committed file
//
// The pack is not built here. zodiacs.org's pack compiler 2.0.0 refits NAIF's
// de440.bsp (KERNEL_SHA256) with --fromYear=1790 --toYear=2210 and seals the
// result (docs/evidence/l1-gap-20261113/README.md, "The kernel and the
// pack", and docs/evidence/de440-20261110/README.md). This script takes that
// file, refuses any other bytes than PACK_SHA256 and PACK_BYTES name, and
// writes them as one base64 string, which is how a package of JavaScript
// modules can carry them to every runtime. --check decodes the committed
// file and holds it to the same digest and size, and to the text this script
// would write. Regenerate the file; never edit it by hand.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

export const PACK_FILE = "de440-1790-2210.v2.zeph";
export const PACK_SHA256 = "51428874d9a47213abc0ff42cbcec65f338624eaa2d8831f0e6ddc3654bf1fa7";
export const PACK_BYTES = 2_489_664;
export const KERNEL_SHA256 = "a4ce9bf9b3282becc9f4b2ac3cebe03a2ae7599981aabd7265fd8482fff7c4b5";
const TARGET = new URL("../src/de440/pack-data.ts", import.meta.url);

const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

/** The text of src/de440/pack-data.ts for the pack's bytes. */
export function moduleText(bytes) {
  assert.equal(bytes.byteLength, PACK_BYTES, `the pack must be ${PACK_BYTES} bytes`);
  assert.equal(sha256(bytes), PACK_SHA256, "the pack's SHA-256 is not the one this script names");
  return (
    `// Generated by scripts/build-de440-pack.mjs from ${PACK_FILE} (sha256 ${PACK_SHA256}, ${PACK_BYTES} bytes), ` +
    `the sealed pack zodiacs.org's compiler 2.0.0 refits from NAIF's de440.bsp (sha256 ${KERNEL_SHA256}): its bytes in base64. Do not edit.\n` +
    `export const DE440_PACK_BASE64: string = "${Buffer.from(bytes).toString("base64")}";\n`
  );
}

/** The pack's bytes as the committed module holds them. */
export function committedBytes(text = readFileSync(TARGET, "utf8")) {
  const match = /^export const DE440_PACK_BASE64: string = "([A-Za-z0-9+/]*={0,2})";$/mu.exec(text);
  assert(match, "src/de440/pack-data.ts does not hold the pack as this script writes it");
  return new Uint8Array(Buffer.from(match[1], "base64"));
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  const argument = process.argv[2];
  if (argument === "--check") {
    const text = readFileSync(TARGET, "utf8");
    assert.equal(text, moduleText(committedBytes(text)), "src/de440/pack-data.ts is not what this script writes");
    console.log(`src/de440/pack-data.ts holds ${PACK_FILE}: ${PACK_BYTES} bytes, sha256 ${PACK_SHA256}`);
  } else {
    assert(argument, "usage: node scripts/build-de440-pack.mjs <path to the sealed pack> | --check");
    const text = moduleText(new Uint8Array(readFileSync(argument)));
    writeFileSync(TARGET, text);
    console.log(`wrote src/de440/pack-data.ts: ${Buffer.byteLength(text)} bytes of text for ${PACK_BYTES} bytes of pack`);
  }
}
