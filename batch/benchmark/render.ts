import type { Sample, summarize } from "./model.js";

interface ReportView {
  profile: string;
  complete: boolean;
  startedAt: string;
  finishedAt: string | null;
  samples: readonly Sample[];
  summary: ReturnType<typeof summarize>;
}

// Display truncates positive figures, preserving full precision in the JSON.
function display(value: number | null, places = 1): string {
  if (value === null) return "unavailable";
  const scale = 10 ** places;
  return (Math.floor(value * scale) / scale).toFixed(places);
}

export function renderReport(report: ReportView, jsonName: string): string {
  const rows = report.summary.map((row) => `| ${row.backend} | ${row.workload} | ${row.workers} | ${row.samples} | ${row.failedSamples} | ${display(row.medianRowsPerSecond)} | ${display(row.minRowsPerSecond)} to ${display(row.maxRowsPerSecond)} | ${display(row.speedupVsOneWorker, 2)} |`);
  return `# Batch worker scaling observation

Generated by batch/scripts/benchmark.mjs. All figures below come from
[the measured JSON](${jsonName}), which records the source hashes, runtime,
CPU allocation, exact synthetic inputs, per-job durations and failures.

Profile: ${report.profile}. Complete: ${report.complete}.
Started: ${report.startedAt}. Finished: ${report.finishedAt ?? "unfinished"}.
Recorded samples: ${report.samples.length}. Failed samples:
${report.samples.filter((sample) => sample.status !== "ok").length}.

Each rate counts committed result rows, using the sum of the measured job
intervals in a sample. A chart row is a natal chart; a transit row is a
birth/sample snapshot; a matrix row is a directed pair. Rates are comparable
across worker counts within a backend and workload, not across row kinds.
The median and range describe the recorded repetitions, not confidence bounds.
Speedup divides a group's median rate by the same backend and workload's
one-worker median. Displayed figures are truncated; JSON retains full precision.

| Backend | Workload | Workers | Samples | Failed | Median rows/s | Observed rows/s range | Speedup |
| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |
${rows.join("\n")}

The measured path includes submission, claims, worker calculation and transport,
ordered single-row commits and SQLite file-size guard checks. Stores are fresh
for each bounded job; workers stay warm within a sample. Pool warmup, database
opening and closing, verification, exports, cleanup and gaps are outside the
interval. Sample wall times are also recorded and include those operations.

This is repeated small-job throughput on the observed machine. It does not
establish large-single-job scaling, continuous service throughput, HTTP or CLI
throughput, cold-start performance, physical astronomy accuracy, or performance
on an exclusive host. CPU affinity and visible quotas do not establish exclusive
CPU capacity. Read the JSON method and machine fields before comparing runs.
`;
}
