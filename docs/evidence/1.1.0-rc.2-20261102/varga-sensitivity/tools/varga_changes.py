#!/usr/bin/env python3
"""F1, the change fixture of the varga sensitivity check (PREREGISTRATION.md,
section 6).

Writes src/vedic/fixtures/varga-changes.json. For each of the 18 keys (the
sixteen Parashari vargas, and the cyclic D2 and D3) it lists every part
boundary T, a whole number of ticks of 1/7560 degree, with the sign on the
tick below T and the sign at T, and whether they differ: a change boundary
when they do, a keep when they do not.

The rules are not restated here. They are imported from
docs/evidence/vedic-2026-09-28/tools/boundary_fixtures.py (varga_sign and
boundary_ticks, lines 144 to 179 at engine main a253973), the engine-free
generator of src/vedic/fixtures/boundaries.json, which transcribes BPHS ch. 6
as tables. Signs are computed there with exact rational arithmetic
(fractions.Fraction):

  below = the sign at the exact rational (T - 1) / 7560, the tick below T,
          taken round the circle (for T = 0, the tick 2,721,599, just below
          360 degrees);
  at    = the sign at the exact rational T / 7560.

Nothing here imports or runs the engine, and boundaries.json is not touched.

Usage: python3 -I -B varga_changes.py [--output PATH] [--check]
  --check compares the generated bytes with the file at PATH instead of
  writing it, and exits 1 if they differ.
"""
import argparse
import hashlib
import json
import sys
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parents[5]
RULES = ROOT / "docs/evidence/vedic-2026-09-28/tools"

# Import the transcribed rules without writing bytecode into that folder.
sys.dont_write_bytecode = True
sys.path.insert(0, str(RULES))
import boundary_fixtures as rules  # noqa: E402

TICKS = rules.TICKS
CIRCLE = 360 * TICKS
KEYS = list(rules.DIVISIONS) + ["D2cyclic", "D3cyclic"]


def rows_for(key):
    """[T, sign index below, sign index at, 1 if they differ else 0] for every part boundary of `key`."""
    out = []
    for t in rules.boundary_ticks(key):
        below = rules.varga_sign(key, Fraction((t - 1) % CIRCLE, TICKS)) - 1
        at = rules.varga_sign(key, Fraction(t, TICKS)) - 1
        out.append([t, below, at, 1 if below != at else 0])
    return out


def build():
    varga = {key: rows_for(key) for key in KEYS}
    counts = {}
    for key, rows in varga.items():
        changes = sum(row[3] for row in rows)
        counts[key] = {"boundaries": len(rows), "changes": changes, "keeps": len(rows) - changes}
    total = {
        "boundaries": sum(c["boundaries"] for c in counts.values()),
        "changes": sum(c["changes"] for c in counts.values()),
        "keeps": sum(c["keeps"] for c in counts.values()),
    }
    return {
        "generator": "docs/evidence/1.1.0-rc.2-20261102/varga-sensitivity/tools/varga_changes.py",
        "rules": "docs/evidence/vedic-2026-09-28/tools/boundary_fixtures.py (varga_sign, boundary_ticks)",
        "ticksPerDegree": TICKS,
        "columns": ["T", "signIndexBelow", "signIndexAt", "change"],
        "below": "the sign at the exact rational (T - 1) / 7560, taken round the circle (for T = 0, 2721599 / 7560)",
        "at": "the sign at the exact rational T / 7560",
        "change": "1 when the two signs differ (a change boundary), 0 when they are the same (a keep)",
        "keys": KEYS,
        "total": total,
        "counts": counts,
        "varga": varga,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", default=str(ROOT / "src/vedic/fixtures/varga-changes.json"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = build()
    text = json.dumps(data, separators=(",", ":")) + "\n"
    digest = hashlib.sha256(text.encode()).hexdigest()
    keeps = {key: [row[0] for row in rows if row[3] == 0] for key, rows in data["varga"].items()}
    summary = {
        "output": args.output,
        "sha256": digest,
        "total": data["total"],
        "counts": data["counts"],
        "keepsInDegrees": {key: [t / TICKS for t in ticks] for key, ticks in keeps.items() if ticks},
    }
    if args.check:
        same = Path(args.output).read_bytes() == text.encode()
        summary["check"] = "identical" if same else "DIFFERENT"
        print(json.dumps(summary, indent=1))
        sys.exit(0 if same else 1)
    Path(args.output).write_text(text)
    print(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
