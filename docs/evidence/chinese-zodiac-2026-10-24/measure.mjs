// Compares the Li Chun instants of tools/chinese-zodiac with the committed
// independent references (references.json) and writes results.json.
// tools/chinese-zodiac/selftest.mjs recomputes this and fails if results.json
// differs, so the figures quoted in the documentation stay tied to the code.
// Run: node docs/evidence/chinese-zodiac-2026-10-24/measure.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { liChunTerrestrialMs, liChunUtcMs } from '../../../tools/chinese-zodiac/li-chun.mjs';
import { BOUNDARY_UNCERTAINTY_SECONDS } from '../../../tools/chinese-zodiac/index.mjs';

const round1 = (x) => Math.round(x * 10) / 10;

function stats(rows) {
  const values = rows.map((row) => row.seconds);
  const abs = values.map(Math.abs);
  const worst = rows[abs.indexOf(Math.max(...abs))];
  return {
    count: values.length,
    years: [rows[0].year, rows.at(-1).year],
    maxAbsSeconds: round1(Math.max(...abs)),
    worstYear: worst.year,
    meanSeconds: round1(values.reduce((a, b) => a + b, 0) / values.length),
  };
}

export function measure(references) {
  const horizons = references.horizons.liChun;
  const ut = horizons.map((e) => ({ year: e.year, seconds: (liChunUtcMs(e.year) - Date.parse(e.ut)) / 1000 }));
  const tt = horizons.map((e) => ({
    year: e.year,
    seconds: (liChunTerrestrialMs(e.year) - (Date.parse(e.ut) + e.tdbMinusUtSeconds * 1000)) / 1000,
  }));
  const hko = references.hko.liChun.map((e) => ({ year: e.year, seconds: (liChunUtcMs(e.year) - Date.parse(e.utc)) / 1000 }));
  const horizonsVsHko = references.hko.liChun.map((e) => ({
    year: e.year,
    seconds: (Date.parse(horizons.find((h) => h.year === e.year).ut) - Date.parse(e.utc)) / 1000,
  }));
  const chinaDates = {};
  for (const e of horizons) {
    const day = new Date(Date.parse(e.ut) + 8 * 3_600_000).getUTCDate();
    const key = `February ${day}`;
    chinaDates[key] = (chinaDates[key] ?? 0) + 1;
  }
  return {
    description: 'Computed Li Chun minus reference Li Chun, seconds. Generated by measure.mjs; do not edit by hand.',
    boundaryUncertaintySeconds: BOUNDARY_UNCERTAINTY_SECONDS,
    computedVsHorizonsUT: stats(ut),
    computedVsHorizonsUT1900to2026: stats(ut.filter((r) => r.year <= 2026)),
    computedVsHorizonsUT2027to2100: stats(ut.filter((r) => r.year >= 2027)),
    computedVsHorizonsTT: stats(tt),
    computedVsHko: stats(hko),
    horizonsVsHko: stats(horizonsVsHko),
    horizonsLiChunDateInChinaStandardTime: chinaDates,
  };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const references = JSON.parse(readFileSync(new URL('./references.json', import.meta.url), 'utf8'));
  writeFileSync(new URL('./results.json', import.meta.url), JSON.stringify(measure(references), null, 1) + '\n');
}
