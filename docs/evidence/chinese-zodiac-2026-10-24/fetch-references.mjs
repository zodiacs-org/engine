// Fetches the independent references for the Li Chun boundary used by
// tools/chinese-zodiac and writes references.json beside this script.
//
// 1. JPL Horizons (DE441): apparent geocentric ecliptic longitude of the Sun
//    of date (QUANTITIES 31, airless), hourly from February 2 00:00 to
//    February 6 00:00 UT of every year 1900 to 2100. The 315 degree crossing
//    is interpolated linearly between the two bracketing hourly samples.
// 2. Hong Kong Observatory: the published 24 solar terms for every year its
//    site serves as XML (Hong Kong Time, UTC+8, to the minute). Only the
//    Li Chun (third) entry of each year is kept.
//
// Raw responses are not committed; their SHA-256 digests are recorded.
// Run: node docs/evidence/chinese-zodiac-2026-10-24/fetch-references.mjs
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';

const FIRST = 1900, LAST = 2100;
const HKO_PROBE = { first: 2000, last: 2040 };
const sha256 = (text) => createHash('sha256').update(text).digest('hex');
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const MONTHS = { Jan: 0, Feb: 1, Mar: 2, Apr: 3, May: 4, Jun: 5, Jul: 6, Aug: 7, Sep: 8, Oct: 9, Nov: 10, Dec: 11 };

function horizonsUrl(year) {
  const params = {
    format: 'text', COMMAND: "'10'", OBJ_DATA: "'NO'", MAKE_EPHEM: "'YES'",
    EPHEM_TYPE: "'OBSERVER'", CENTER: "'500@399'",
    START_TIME: `'${year}-02-02 00:00'`, STOP_TIME: `'${year}-02-06 00:00'`,
    STEP_SIZE: "'1h'", QUANTITIES: "'30,31'", CSV_FORMAT: "'YES'",
    TIME_TYPE: "'UT'", EXTRA_PREC: "'YES'", ANG_FORMAT: "'DEG'",
  };
  return 'https://ssd.jpl.nasa.gov/api/horizons.api?' + new URLSearchParams(params).toString();
}

function parseHorizons(text, year) {
  const body = text.split('$$SOE')[1]?.split('$$EOE')[0];
  if (!body) throw new Error(`Horizons ${year}: no ephemeris block`);
  if (!/source: DE441/.test(text)) throw new Error(`Horizons ${year}: not DE441`);
  const rows = body.trim().split('\n').map((line) => {
    const cells = line.split(',').map((cell) => cell.trim());
    const match = /^(\d{4})-(\w{3})-(\d{2}) (\d{2}):(\d{2})$/.exec(cells[0]);
    if (!match) throw new Error(`Horizons ${year}: bad time ${cells[0]}`);
    const t = Date.UTC(Number(match[1]), MONTHS[match[2]], Number(match[3]), Number(match[4]), Number(match[5]));
    return { t, tdbMinusUt: Number(cells[3]), lon: Number(cells[4]) };
  });
  for (let i = 1; i < rows.length; i++) {
    const a = rows[i - 1], b = rows[i];
    if (a.lon < 315 && b.lon >= 315) {
      const fraction = (315 - a.lon) / (b.lon - a.lon);
      const ut = a.t + fraction * (b.t - a.t);
      const tdbMinusUt = a.tdbMinusUt + fraction * (b.tdbMinusUt - a.tdbMinusUt);
      return { ut: new Date(Math.round(ut)).toISOString(), tdbMinusUtSeconds: Number(tdbMinusUt.toFixed(6)) };
    }
  }
  throw new Error(`Horizons ${year}: no 315 degree crossing in the window`);
}

async function get(url) {
  for (let attempt = 1; ; attempt++) {
    try {
      const response = await fetch(url);
      const text = await response.text();
      return { status: response.status, text };
    } catch (error) {
      if (attempt >= 4) throw error;
      await sleep(2000 * attempt);
    }
  }
}

const horizons = [];
const eopLines = new Set();
for (let year = FIRST; year <= LAST; year++) {
  const { status, text } = await get(horizonsUrl(year));
  if (status !== 200) throw new Error(`Horizons ${year}: HTTP ${status}`);
  horizons.push({ year, ...parseHorizons(text, year), sha256: sha256(text) });
  for (const line of text.split('\n')) if (/^EOP (?:file|coverage)\s*:/.test(line)) eopLines.add(line.trim().replace(/\s+/g, ' '));
  process.stderr.write(`horizons ${year}\n`);
  await sleep(300);
}

const hko = [];
for (let year = HKO_PROBE.first; year <= HKO_PROBE.last; year++) {
  const url = `https://www.hko.gov.hk/en/gts/astronomy/data/files/24SolarTerms_${year}.xml`;
  const { status, text } = await get(url);
  if (status === 404) continue;
  if (status !== 200) throw new Error(`HKO ${year}: HTTP ${status}`);
  const entries = [...text.matchAll(/<Data><M>(\d{2})<\/M><D>(\d{2})<\/D><hm>(\d{2}):(\d{2})<\/hm><\/Data>/g)];
  if (entries.length !== 24) throw new Error(`HKO ${year}: ${entries.length} terms`);
  const [, month, day, hour, minute] = entries[2];
  if (month !== '02') throw new Error(`HKO ${year}: third term is not in February`);
  const utc = new Date(Date.UTC(year, 1, Number(day), Number(hour) - 8, Number(minute)));
  hko.push({ year, hkt: `${year}-${month}-${day} ${hour}:${minute}`, utc: utc.toISOString(), url, sha256: sha256(text) });
  process.stderr.write(`hko ${year}\n`);
}

const out = {
  description: 'Independent references for the Li Chun (solar longitude 315 degrees) instant. Generated by fetch-references.mjs; do not edit by hand.',
  fetched: new Date().toISOString().slice(0, 10),
  horizons: {
    source: 'JPL Horizons API, target 10 (Sun), center 500@399 (geocentric), observer table, QUANTITIES 30,31 (TDB-UT and apparent ecliptic longitude and latitude of date), airless, EXTRA_PREC',
    ephemeris: 'DE441',
    sampling: 'hourly, February 2 00:00 to February 6 00:00 UT; 315 degree crossing interpolated linearly between bracketing samples',
    timeScale: 'UT as Horizons reports it: UT1 before 1962, UTC from 1962',
    years: [FIRST, LAST],
    earthOrientation: [...eopLines].sort(),
    liChun: horizons,
  },
  hko: {
    source: 'Hong Kong Observatory, 24 solar terms XML per year (Hong Kong Time, UTC+8, to the minute); third entry of each year (Li Chun)',
    probedYears: [HKO_PROBE.first, HKO_PROBE.last],
    liChun: hko,
  },
};
writeFileSync(new URL('./references.json', import.meta.url), JSON.stringify(out, null, 1) + '\n');
process.stderr.write(`wrote ${horizons.length} Horizons and ${hko.length} HKO entries\n`);
