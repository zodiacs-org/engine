import { createHash } from "node:crypto";

export const BUILD_SECTION = "zodiacs.rustcore.build";

function uleb(value) {
  const bytes = [];
  do {
    const byte = value & 0x7f;
    value >>>= 7;
    bytes.push(byte | (value ? 0x80 : 0));
  } while (value);
  return Buffer.from(bytes);
}

/** Pair generated glue and WASM without instantiating the module at build time. */
export function bindWasmBuild(wasm, glue) {
  const module = new WebAssembly.Module(wasm);
  if (WebAssembly.Module.customSections(module, BUILD_SECTION).length !== 0) {
    throw new Error("WASM build identity already present; regenerate with wasm-bindgen first.");
  }
  // This is an artifact pairing check, not authentication of caller-owned bytes.
  const digest = createHash("sha256").update(wasm).update(glue).digest("hex");
  const name = Buffer.from(BUILD_SECTION);
  const payload = Buffer.concat([uleb(name.length), name, Buffer.from(digest)]);
  const bytes = Buffer.concat([wasm, Buffer.from([0]), uleb(payload.length), payload]);
  const source = "// Generated by scripts/wasm-build.mjs; do not edit.\n" +
    `export const WASM_BUILD_SECTION = ${JSON.stringify(BUILD_SECTION)};\n` +
    `export const WASM_BUILD_ID = ${JSON.stringify(digest)};\n`;
  return { bytes, source, digest };
}
